	hl.exec_cmd("mkdir -p " .. ssDir)
end)

-- Region → clipboard
hl.bind(mainMod .. " + V", hl.dsp.exec_cmd('grim -g "$(slurp)" - | wl-copy'))

-- Full screen → clipboard
